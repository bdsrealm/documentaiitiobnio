  function slug (text) {
    return text.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
  }

  function initChapter () {
    const main = document.querySelector('main')
    if (!main || !main.querySelector('.hero')) return

    const crumb = document.querySelector('.crumb')
    const crumbText = crumb ? crumb.textContent : ''
    const num = (crumbText.match(/§\s*(\d+)/) || [])[1] || ''
    const h2s = [...main.querySelectorAll('h2')]
    if (!h2s.length) return

    main.classList.add('chapter')
    const hero = main.querySelector('.hero')
    if (num) hero.dataset.chapter = num

    h2s.forEach((h) => {
      const label = h.textContent.replace(/§/g, '').replace(/\s+/g, ' ').trim()
      if (!h.id) h.id = slug(label.replace(/^[\d.]+\s*/, ''))
    })

    const lede = hero.querySelector('.lede')
    if (lede && !main.querySelector('.hero-meta')) {
      const words = main.textContent.trim().split(/\s+/).length
      const mins = Math.max(1, Math.round(words / 210))
      const bits = [num ? `§ ${num}` : '', `${h2s.length} sections`, `~${mins} min`].filter(Boolean)
      const meta = document.createElement('p')
      meta.className = 'hero-meta'
      meta.innerHTML = bits.map((t) => `<span>${t}</span>`).join('<i></i>')
      lede.insertAdjacentElement('afterend', meta)
    }

    if (h2s.length > 3 && !main.querySelector('.page-toc')) {
      const toc = document.createElement('nav')
      toc.className = 'page-toc'
      toc.innerHTML = `<div class="pt-head">On this page</div><ol>${h2s.map((h) => {
        const label = h.textContent.replace(/§/g, '').replace(/\s+/g, ' ').trim()
        return `<li><a href="#${h.id}">${label}</a></li>`
      }).join('')}</ol>`
      h2s[0].insertAdjacentElement('beforebegin', toc)
    }

    const idx = CHAPTER_ORDER.findIndex(([, n]) => n === num)
    const next = idx >= 0 ? CHAPTER_ORDER[idx + 1] : null
    if (next && !main.querySelector('.chapter-next')) {
      const box = document.createElement('a')
      box.className = 'chapter-next'
      box.href = next[0]
      box.innerHTML = `<span class="cn-kicker">Next — § ${next[1]}</span>
        <span class="cn-title">${next[2]} <i>→</i></span>`
      main.appendChild(box)
    }
  }

  function initStats () {
    document.querySelectorAll('[data-stat]').forEach((n) => {
      const key = n.dataset.stat
      const v = META[key]
      n.textContent = v != null ? Number(v).toLocaleString() : '—'
    })
    document.querySelectorAll('[data-meta]').forEach((n) => {
      const v = META[n.dataset.meta]
      n.textContent = v != null ? v : '—'
    })
    document.querySelectorAll('[data-version]').forEach((n) => {
      n.textContent = META.gameVersion + ' / ' + META.protocolVersion
    })
  }

